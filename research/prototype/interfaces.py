"""Small contracts shared by the byte model and external inference system."""

from __future__ import annotations

from dataclasses import dataclass
from typing import Any, Protocol


class Tokenizer(Protocol):
    name: str

    def encode(self, text: str) -> list[int]: ...

    def decode(self, token_ids: list[int]) -> str: ...


class Generator(Protocol):
    name: str

    def generate(self, token_ids: list[int], max_new_tokens: int) -> list[int]: ...


class EvidenceStore(Protocol):
    def search(self, query: str, method: str = "bm25", k: int = 3,
               exclude: set[str] | None = None) -> list[dict[str, Any]]: ...


class EvidenceWriter(Protocol):
    def add(self, doc: dict[str, Any]) -> None: ...

    def update(self, doc_id: str, doc: dict[str, Any]) -> None: ...

    def delete(self, doc_id: str) -> None: ...


class Verifier(Protocol):
    def verify(self, query: dict[str, Any], evidence: list[dict[str, Any]]) -> dict[str, Any]: ...


class ByteTokenizer:
    """Lossless UTF-8 byte IDs; decode only after joining all generated bytes."""

    name = "utf8-byte-v1"
    vocab_size = 256

    def encode(self, text: str) -> list[int]:
        return list(text.encode("utf-8"))

    def decode(self, token_ids: list[int]) -> str:
        if any(not 0 <= int(token) < self.vocab_size for token in token_ids):
            raise ValueError("byte token ID outside [0, 255]")
        return bytes(token_ids).decode("utf-8", errors="replace")


@dataclass(frozen=True)
class EvidenceAnswer:
    answer: str | None
    abstained: bool
    citations: tuple[str, ...]
    reason: str
